    if (archivo.exists()) archivo.inputStream().use { load(it) }
}

fun urlBackend(nombre: String): String {
    val url = (project.findProperty(nombre) as String?)?.trim().orEmpty()
    return if (url.endsWith("/")) url else "$url/"
}

